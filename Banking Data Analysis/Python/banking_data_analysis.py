from scipy.stats import ttest_ind, mannwhitneyu
from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score,
    classification_report, confusion_matrix,
    roc_auc_score)

housing_yes = df.loc[df['housing'] == 'yes', 'balance']
housing_no = df.loc[df['housing'] == 'no', 'balance']

# Welch's t-test
t_stat, p_value = ttest_ind(
    housing_yes,
    housing_no,
    equal_var=False)

print("Mean balance (housing loan):", housing_yes.mean())
print("Mean balance (no housing loan):", housing_no.mean())
print("Welch t-statistic:", t_stat)
print("Welch p-value:", p_value)

if p_value < 0.05:
    print("Reject H0: The mean balances differ significantly.")
else:
    print("Fail to reject H0: Insufficient evidence of a mean difference.")

# Additional non-parametric test
u_stat, mw_p_value = mannwhitneyu(
    housing_yes,
    housing_no,
    alternative='two-sided')

print("Mann-Whitney p-value:", mw_p_value)

campaign_cols = ['duration', 'campaign', 'pdays', 'previous', 'y']

