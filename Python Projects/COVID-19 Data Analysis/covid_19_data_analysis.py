import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
from prophet import Prophet

df = pd.read_csv("/content/covid_19_clean_complete.csv")

df

df.shape

df.info()

df.isnull().sum()

df.duplicated().sum()

df['Date'] = pd.to_datetime(df['Date'])

df.info()

daily_cases = df.groupby('Date').agg({'Confirmed': 'sum', 'Deaths': 'sum', 'Recovered': 'sum'}).reset_index()
daily_cases

daily_cases['Active'] = daily_cases['Confirmed'] - daily_cases['Deaths'] - daily_cases['Recovered']
daily_cases

daily_cases['New Cases'] = daily_cases['Confirmed'].diff().fillna(0)
daily_cases

daily_cases['Recovery Rate'] = (daily_cases['Recovered'] / daily_cases['Confirmed']) * 100
daily_cases

daily_cases['Death Rate'] = (daily_cases['Deaths'] / daily_cases['Confirmed']) * 100
daily_cases

"""**Visualization with plotly Library**"""

# Total cases trend

fig1 = px.line(daily_cases,
    x='Date',
    y=['Confirmed', 'Recovered', 'Deaths', 'Active'],
    title='COVID-19 Global Trend Analysis')
fig1.show()

# New infection trend

fig2 = px.line(daily_cases,
    x='Date',
    y='New Cases',
    title='Daily New Infection Trend')
fig2.show()

# Recovery rate trend
fig3 = px.line(daily_cases,
    x='Date',
    y='Recovery Rate',
    title='Rate of Recovery Trend (%)')
fig3.show()

"""**Visualization with Prophet Library**"""

prophet_data = daily_cases[['Date', 'Confirmed']]
prophet_data.columns = ['ds', 'y']

prophet_data

model = Prophet()
model.fit(prophet_data)

future = model.make_future_dataframe(periods=7)
forecast = model.predict(future)

print(forecast[['ds', 'yhat', 'yhat_lower', 'yhat_upper']].tail(7))

fig4 = go.Figure()

# Actual data
fig4.add_trace(go.Scatter(
    x=prophet_data['ds'],
    y=prophet_data['y'],
    mode='lines',
    name='Actual Confirmed Cases'))

# Predicted data
fig4.add_trace(go.Scatter(
    x=forecast['ds'],
    y=forecast['yhat'],
    mode='lines',
    name='Predicted Cases'))

# Confidence interval
fig4.add_trace(go.Scatter(
    x=forecast['ds'],
    y=forecast['yhat_upper'],
    mode='lines',
    name='Upper Bound',
    line=dict(dash='dot')))

fig4.add_trace(go.Scatter(
    x=forecast['ds'],
    y=forecast['yhat_lower'],
    mode='lines',
    name='Lower Bound',
    line=dict(dash='dot')))

fig4.update_layout(
    title='COVID-19 Forecast for Next 7 Days',
    xaxis_title='Date',
    yaxis_title='Confirmed Cases')

fig4.show()