import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.linear_model import LinearRegression
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error, r2_score

insurance = pd.read_csv('/content/insurance_data.csv')
insurance

insurance.info()

insurance.isnull().sum()

for col in insurance.columns:
  if insurance[col].dtype == 'object':
     insurance[col]= insurance[col].fillna(insurance[col].mode()[0])
  else:
     insurance[col]= insurance[col].fillna(insurance[col].mean())

insurance.columns

insurance.isnull().sum().sum()

insurance.duplicated().sum()

for col in insurance.columns:
  if insurance[col].dtype!='object':
    plt.boxplot(insurance[col])
    plt.xlabel(col)
    plt.show()

out_list = ['bmi','past_consultations','Hospital_expenditure','Anual_Salary']

for column in out_list:
    Q1 = insurance[column].quantile(0.25)
    Q3 = insurance[column].quantile(0.75)
    IQR = Q3 - Q1
    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR
    insurance = insurance[(insurance[column] >= lower_bound) & (insurance[column] <= upper_bound)]

from sklearn.preprocessing import LabelEncoder

LE = LabelEncoder()
for col in insurance.columns:
  if insurance[col].dtype == 'object':
    insurance[col] = LE.fit_transform(insurance[col])

insurance

x = insurance.drop(columns = 'charges')
y = insurance['charges']

x_train, x_test, y_train, y_test = train_test_split(x,y, test_size = 0.2, random_state = 100)

lin_reg = LinearRegression()
lin_reg.fit(x_train, y_train)

lin_reg.coef_

lin_reg.intercept_

y_pred = lin_reg.predict(x_test)

pd.DataFrame({'Actual':y_test, 'Predicted':y_pred})

accuracy = r2_score (y_test, y_pred)
accuracy * 100

mse = mean_squared_error(y_test, y_pred)
mse

rmse = np.sqrt(mse)
rmse