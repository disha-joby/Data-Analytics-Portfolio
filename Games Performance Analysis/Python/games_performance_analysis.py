"""- Hypothesis Testing"""

from scipy.stats import f_oneway

# Group user ratings by platform
platform_groups = []

for platform in df['Platform'].unique():
    ratings = df[df['Platform'] == platform]['User Rating']
    platform_groups.append(ratings)

# Perform One-Way ANOVA test
f_stat, p_value = f_oneway(*platform_groups)

print("F-Statistic:", f_stat)
print("P-Value:", p_value)

# Interpret the result
if p_value < 0.05:
    print("Reject the null hypothesis.")
    print("There is a significant difference in user ratings between platforms.")
else:
    print("Fail to reject the null hypothesis.")
    print("There is no significant difference in user ratings between platforms.")

